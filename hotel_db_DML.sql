DELIMITER $$

-- PAYMENT: Payment_ID 자동 채번 ('00001' 형식)
CREATE TRIGGER TRG_PAYMENT_AUTO_ID
BEFORE INSERT ON PAYMENT
FOR EACH ROW
BEGIN
    IF NEW.Payment_ID IS NULL OR NEW.Payment_ID = '' THEN
        UPDATE SEQ_PaymentID SET next_val = LAST_INSERT_ID(next_val + 1) WHERE id = 1;
        SET NEW.Payment_ID = LPAD(LAST_INSERT_ID(), 5, '0');
    END IF;
END$$

-- INVENTORY: Purchase_ID 자동 채번
CREATE TRIGGER TRG_INVENTORY_AUTO_ID
BEFORE INSERT ON INVENTORY
FOR EACH ROW
BEGIN
    IF NEW.Purchase_ID IS NULL OR NEW.Purchase_ID = '' THEN
        UPDATE SEQ_PurchaseID SET next_val = LAST_INSERT_ID(next_val + 1) WHERE id = 1;
        SET NEW.Purchase_ID = LAST_INSERT_ID();
    END IF;
END$$

-- BOOK: Booking_ID 자동 채번 ('BK00001' 형식)
CREATE TRIGGER TRG_BOOK_AUTO_ID
BEFORE INSERT ON BOOK
FOR EACH ROW
BEGIN
    IF NEW.Booking_ID IS NULL OR NEW.Booking_ID = '' THEN
        UPDATE SEQ_BookingID SET next_val = LAST_INSERT_ID(next_val + 1) WHERE id = 1;
        SET NEW.Booking_ID = CONCAT('BK', LPAD(LAST_INSERT_ID(), 5, '0'));
    END IF;
END$$

-- PAYMENT: 결제 발생 시 로열티 포인트 자동 적립 (10달러당 1포인트)
CREATE TRIGGER TRG_PAYMENT_LOYALTY
AFTER INSERT ON PAYMENT
FOR EACH ROW
BEGIN
    UPDATE GUEST
    SET Loyalty_pts = Loyalty_pts + FLOOR(NEW.Payment_amt / 10)
    WHERE Guest_ID = NEW.Payer_ID;
END$$

-- PAYMENT: 결제 금액 음수 방지
CREATE TRIGGER TRG_PAYMENT_VALIDATE
BEFORE INSERT ON PAYMENT
FOR EACH ROW
BEGIN
    IF NEW.Payment_amt < 0 THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'Payment amount cannot be negative';
    END IF;
END$$

-- BOOK: 체크아웃 날짜가 체크인 날짜보다 빠르면 예약 생성 차단
CREATE TRIGGER TRG_BOOK_DATE_VALIDATE
BEFORE INSERT ON BOOK
FOR EACH ROW
BEGIN
    IF NEW.End_date < NEW.Start_date THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'End_date cannot be earlier than Start_date';
    END IF;
END$$

